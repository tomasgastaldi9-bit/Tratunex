const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const { chromium } = require('playwright');
(async () => {
  const root = __dirname;
  const data = JSON.parse(fs.readFileSync(path.join(root, '../mocks/fixtures.json'), 'utf8'));
  const first = data.companies[0].id;
  const second = data.companies[1].id;
  const counts = { steps: 0 };
  const check = (name, assertion) => { assert.ok(assertion, name); counts.steps++; console.log('PASS ' + name); };
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(pathToFileURL(path.join(root, 'index.html')).href);
    await page.waitForSelector('.pipeline-board');
    await page.evaluate(() => document.fonts.ready);
    check('local Inter font is loaded', await page.evaluate(() => {
      const font = Array.from(document.fonts).find(face => face.family.replace(/"/g, '') === 'Inter');
      return font?.status === 'loaded' && getComputedStyle(document.body).fontFamily.includes('Inter');
    }));
    check('seven exact pipeline stages', await page.locator('.pipeline-column').count() === 7);
    check('first company has own opportunities', await page.locator('.deal-card').count() === data.deals.filter(item => item.company_id === first).length);
    const multiple = data.contacts.find(person => person.company_id === first && data.deals.filter(deal => deal.contact_id === person.id).length > 1);
    const multipleDeals = data.deals.filter(deal => deal.contact_id === multiple.id && deal.company_id === first);
    for (const deal of multipleDeals) {
      const card = page.locator('.pipeline-column[data-stage=' + deal.stage + '] .deal-card').filter({ hasText: multiple.name });
      const expected = data.tasks.some(task => task.company_id === first && task.contact_id === multiple.id && task.deal_id === deal.id && ['pending','running'].includes(task.status));
      check('card task belongs to deal ' + deal.stage, await card.locator('.card-next').count() === (expected ? 1 : 0));
    }
    check('desktop has no page overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.locator('#pipeline-search').fill('no-such-fixture-829');
    check('search empty result', await page.locator('.deal-card').count() === 0);
    await page.locator('#pipeline-search').fill('');
    await page.selectOption('#view-state', 'loading');
    check('loading state', await page.locator('.skeleton').count() === 2);
    await page.selectOption('#view-state', 'empty');
    check('empty state', await page.locator('[data-action=restore]').count() === 1);
    await page.selectOption('#view-state', 'error');
    check('error state', await page.locator('section[role=alert]').count() === 1);
    await page.locator('[data-action=restore]').click();
    check('retry restores data', await page.locator('.pipeline-board').count() === 1);
    await page.locator('.deal-card').first().click();
    await page.waitForSelector('.contact-grid');
    check('contact details from card', await page.locator('.contact-heading h1').count() === 1);
    check('call remains disabled', await page.locator('button[disabled]').count() >= 1);
    const noTask = data.contacts.find(person => person.company_id === first && !data.tasks.some(task => task.company_id === first && task.contact_id === person.id && ['pending','running'].includes(task.status)));
    await page.selectOption('#contact-select', noTask.id);
    await page.waitForFunction(id => location.hash.endsWith(id), noTask.id);
    check('contact without next task', (await page.locator('.contact-aside').innerText()).includes('No hay acciones pendientes'));
    const unknownContact = data.contacts.find(person => person.company_id === first && data.call_previews.some(call => call.contact_id === person.id && call.status === 'unknown'));
    await page.selectOption('#contact-select', unknownContact.id);
    await page.waitForFunction(id => location.hash.endsWith(id), unknownContact.id);
    check('latest unknown alert survives old result', await page.locator('.unknown-alert').count() === 1 && (await page.locator('.unknown-alert').innerText()).includes('antes de iniciar otra llamada'));
    check('old final result retained under unknown alert', await page.locator('.classification').count() === 1);
    await page.locator('[data-nav=tasks]').click();
    await page.waitForSelector('#task-filter');
    await page.selectOption('#task-filter', 'all');
    const rowsFirst = data.tasks.filter(task => task.company_id === first).length;
    check('all task statuses visible', await page.locator('.task-table tbody tr').count() === rowsFirst);
    check('undated task explicit', (await page.locator('#tasks-content').innerText()).includes('Fecha por definir'));
    await page.selectOption('#task-filter', 'human_review');
    check('human review filter', await page.locator('.task-table tbody tr').count() === data.tasks.filter(task => task.company_id === first && task.kind === 'human_review').length);
    await page.selectOption('#company-select', second);
    check('second company task data only', await page.locator('.task-table tbody tr').count() === data.tasks.filter(task => task.company_id === second && task.kind === 'human_review').length);
    await page.locator('[data-nav=pipeline]').click();
    await page.waitForSelector('.pipeline-board');
    check('company switch opportunities isolated', await page.locator('.deal-card').count() === data.deals.filter(item => item.company_id === second).length);
    for (const person of data.contacts.filter(item => item.company_id === first)) check('first company name absent: ' + person.name, !(await page.locator('main').innerText()).includes(person.name));
    const firstContact = data.contacts.find(item => item.company_id === first);
    await page.evaluate(id => location.hash = '#/contacts/' + id, firstContact.id);
    await page.waitForSelector('.state-panel');
    check('foreign contact blocked visually', await page.locator('.contact-grid').count() === 0);
    await page.selectOption('#company-select', first);
    await page.waitForSelector('.contact-grid');
    await page.locator('[data-nav=pipeline]').click();
    await page.waitForSelector('.pipeline-board');
    await page.locator('[data-pipeline-view=list]').click();
    check('list shows own opportunities', await page.locator('.deal-table tbody tr').count() === data.deals.filter(item => item.company_id === first).length);
    check('list view is announced as selected', await page.locator('[data-pipeline-view=list]').getAttribute('aria-pressed') === 'true');
    await page.locator('#pipeline-search').fill(multiple.name);
    check('list search preserves multiple deals per contact', await page.locator('.deal-table tbody tr').count() === multipleDeals.length);
    await page.locator('#pipeline-search').fill('no-such-fixture-829');
    check('list search empty result is explicit', await page.locator('.deal-table tbody tr').count() === 0 && await page.locator('.search-feedback').count() === 1);
    await page.selectOption('#company-select', second);
    check('company switch clears list search', await page.locator('#pipeline-search').inputValue() === '');
    check('list switches company data', await page.locator('.deal-table tbody tr').count() === data.deals.filter(item => item.company_id === second).length);
    check('list excludes previous company', !(await page.locator('.deal-table').innerText()).includes(multiple.name));
    await page.locator('.deal-table tbody a').first().click();
    await page.waitForSelector('.contact-grid');
    check('list opens contact details', await page.locator('.contact-heading h1').count() === 1);
    await page.selectOption('#company-select', first);
    await page.locator('[data-nav=pipeline]').click();
    await page.waitForSelector('[data-pipeline-view=board]');
    await page.locator('[data-pipeline-view=board]').click();
    check('return to board preserves seven stages', await page.locator('.pipeline-column').count() === 7);
    fs.mkdirSync(path.join(root, 'previews'), { recursive: true });
    await page.screenshot({ path: path.join(root, 'previews/desktop.png'), fullPage: true });
    const rich = data.contacts.find(person => person.company_id === first && data.tasks.some(task => task.company_id === first && task.contact_id === person.id && ['pending','running'].includes(task.status)) && data.call_results.some(result => result.company_id === first && result.contact_id === person.id));
    await page.evaluate(id => location.hash = '#/contacts/' + id, rich.id);
    await page.waitForSelector('.contact-grid');
    await page.screenshot({ path: path.join(root, 'previews/contact.png'), fullPage: true });
    await page.locator('[data-nav=tasks]').click();
    await page.waitForSelector('#task-filter');
    await page.selectOption('#task-filter', 'all');
    await page.screenshot({ path: path.join(root, 'previews/tasks.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    check('mobile tasks no page overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.evaluate(id => location.hash = '#/contacts/' + id, rich.id);
    await page.waitForSelector('.contact-grid');
    check('mobile contact no page overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: path.join(root, 'previews/mobile.png'), fullPage: true });
    await page.locator('[data-nav=pipeline]').click();
    await page.waitForSelector('.pipeline-board');
    check('mobile pipeline no page overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    check('mobile board scroll region preserved', await page.locator('.board-scroll').evaluate(element => element.scrollWidth > element.clientWidth));

    for (const width of [1440, 1024, 768, 390, 320]) {
      await page.setViewportSize({ width, height: 1000 });
      for (const view of ['board', 'list']) {
        await page.locator('[data-pipeline-view=' + view + ']').click();
        check('pipeline ' + view + ' fits ' + width + 'px', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
      }
      await page.evaluate(id => location.hash = '#/contacts/' + id, rich.id);
      await page.waitForSelector('.contact-grid');
      check('contact fits ' + width + 'px', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
      await page.locator('[data-nav=tasks]').click();
      await page.waitForSelector('#task-filter');
      check('tasks fit ' + width + 'px', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
      await page.locator('[data-nav=pipeline]').click();
      await page.waitForSelector('[data-pipeline-view=board]');
    }

    const primary = await page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--color-primary').trim());
    const guideUrl = await page.locator('.guide-link').evaluate(link => link.href);
    const guide = await browser.newPage();
    guide.on('pageerror', error => errors.push(error.message));
    await guide.goto(guideUrl);
    await guide.waitForSelector('h1');
    check('shared gallery link resolves', (await guide.locator('h1').innerText()).includes('Sistema de diseño'));
    check('gallery uses same primary token', primary === await guide.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--color-primary').trim()));
    await guide.locator('.library-back').click();
    await guide.waitForSelector('.pipeline-board');
    check('gallery returns to CRM', await guide.locator('.pipeline-column').count() === 7);
    await guide.close();
    check('no runtime errors', errors.length === 0);
    console.log(JSON.stringify({ total: counts.steps, errors, screenshots: ['desktop.png','contact.png','tasks.png','mobile.png'] }));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
